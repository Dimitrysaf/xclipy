#!/usr/bin/python3
"""Regenerate xclipy/emoji_data.py from Unicode's emoji-test.txt.

    curl -O https://unicode.org/Public/emoji/latest/emoji-test.txt
    python3 tools/update_emoji.py emoji-test.txt

Only fully-qualified emoji up to --max-version are kept (newer ones show as
empty boxes with the emoji font most desktops have). Skin tone variants are
kept apart, for the emoji that have one for each tone (not the mixed ones,
like two people with different skin tones).
"""

import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "xclipy", "emoji_data.py")
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$")
SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
TONE_NAMES = ("light skin tone", "medium-light skin tone", "medium skin tone",
              "medium-dark skin tone", "dark skin tone")
SKIPPED_GROUPS = {"Component"}


def without_tone(name):
    """("waving hand", tone index) for "waving hand: medium skin tone", else None.

    Other details stay: "man: medium skin tone, beard" is "man: beard".
    """
    base, _colon, details = name.partition(": ")
    details = details.split(", ") if details else []
    tones = {TONE_NAMES.index(d) for d in details if d in TONE_NAMES}
    if len(tones) != 1:
        return None
    rest = [d for d in details if d not in TONE_NAMES]
    return (base + ": " + ", ".join(rest) if rest else base), tones.pop()


def parse(path, max_version):
    groups, emoji, toned = [], [], {}
    group = None
    with open(path, encoding="utf-8") as stream:
        for line in stream:
            if line.startswith("# group: "):
                group = line[9:].strip()
                if group not in SKIPPED_GROUPS:
                    groups.append(group)
                continue
            match = LINE.match(line.strip())
            if not match or group in SKIPPED_GROUPS or float(match.group(3)) > max_version:
                continue
            codepoints = [int(c, 16) for c in match.group(1).split()]
            if SKIN_TONES.intersection(codepoints):
                found = without_tone(match.group(4))
                if found is not None:
                    toned.setdefault(found[0], {})[found[1]] = match.group(2)
                continue
            emoji.append((groups.index(group), match.group(2), match.group(4)))
    tones = {}
    for _group, text, name in emoji:
        variants = toned.get(name, {})
        if len(variants) == len(TONE_NAMES):
            tones[text] = tuple(variants[index] for index in range(len(TONE_NAMES)))
    return groups, emoji, tones


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("emoji_test")
    parser.add_argument("--max-version", type=float, default=15.1)
    args = parser.parse_args()
    groups, emoji, tones = parse(args.emoji_test, args.max_version)
    with open(OUTPUT, "w", encoding="utf-8") as stream:
        stream.write('"""Emoji {} in CLDR order. Generated by tools/update_emoji.py, do not edit."""\n\n'
                     .format(args.max_version))
        stream.write("GROUPS = (\n")
        for name in groups:
            stream.write("    {!r},\n".format(name))
        stream.write(")\n\n# (group index, emoji, English name)\nEMOJI = (\n")
        for group, text, name in emoji:
            stream.write("    ({}, {!r}, {!r}),\n".format(group, text, name))
        stream.write(")\n\n# emoji: its light, medium-light, medium, medium-dark and dark skin tones\nTONES = {\n")
        for text, variants in tones.items():
            stream.write("    {!r}: {!r},\n".format(text, variants))
        stream.write("}\n")
    print("{} emoji in {} groups, {} with skin tones".format(len(emoji), len(groups), len(tones)))


if __name__ == "__main__":
    main()
